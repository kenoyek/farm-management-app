"""Reproduce the source audit without evaluating untrusted Excel formulas."""
import hashlib,json,pathlib,openpyxl
root=pathlib.Path(__file__).resolve().parents[1]
books=[]
for path in sorted((root/'data/source').glob('*.xlsx')):
    w=openpyxl.load_workbook(path,data_only=False); cached=openpyxl.load_workbook(path,data_only=True)
    b={'file':path.name,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'sheets':[]}
    for s in w:
        cells=[{'cell':c.coordinate,'value':c.value,'format':c.number_format,**({'cached':cached[s.title][c.coordinate].value} if c.data_type=='f' else {})} for row in s for c in row if c.value is not None]
        b['sheets'].append({'name':s.title,'rows':s.max_row,'columns':s.max_column,'formula_count':sum(c.data_type=='f' for row in s for c in row),'cells':cells})
    books.append(b)
(root/'data/workbook-audit.json').write_text(json.dumps(books,indent=2,ensure_ascii=False,default=str))
lines=['# Complete workbook cell inventory','','Generated by `python scripts/inspect_workbooks.py`. Formulas are preserved, never executed. Cached values may be stale. Blank cells are absent from this inventory; missing is not zero. Source files are retained with hashes.','']
for b in books:
    lines.extend([f"## {b['file']}",f"SHA-256: `{b['sha256']}`",''])
    for s in b['sheets']:
        lines.extend([f"### {s['name']}",f"Used extent: {s['rows']} rows × {s['columns']} columns; {s['formula_count']} formula cells.",'','| Cell | Source value / formula | Cached result | Number format |','|---|---|---|---|'])
        for c in s['cells']:
            esc=lambda x:str(x).replace('|','\\|').replace('\n',' ')
            lines.append('| '+' | '.join(esc(c.get(k,'')) for k in ['cell','value','cached','format'])+' |')
        lines.append('')
(root/'docs/WORKBOOK_CELL_INVENTORY.md').write_text('\n'.join(lines))
# Explicit row mapping, preserving missing data. No scientific values are approved.
w=openpyxl.load_workbook(root/'data/source/Feed Formula Calculator.xlsx',data_only=True)
s=w['Nutritional Intake']; nutrients=['energy','protein','dryMatter','calcium','phosphorus','methionine','lysine']
ingredients=[]
for r in range(7,39):
    ingredients.append({'id':f'wb-{r}','name':s.cell(r,2).value,'source':f'Feed Formula Calculator.xlsx / Nutritional Intake!B{r}:J{r}','reviewStatus':'unverified','nutrients':{n:s.cell(r,c).value for n,c in zip(nutrients,range(3,10))},'price':s.cell(r,10).value})
(root/'data/ingredients.json').write_text(json.dumps(ingredients,indent=2,ensure_ascii=False))
print('Audited',len(books),'workbooks;',sum(len(b['sheets']) for b in books),'sheets')
